import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(new URL('../../timeline/functions/package.json', import.meta.url));
const { initializeApp } = require('firebase-admin/app');
const { getFirestore } = require('firebase-admin/firestore');
const { getAuth } = require('firebase-admin/auth');
Object.assign(process.env, { GCLOUD_PROJECT: 'demo-timeline', FIRESTORE_EMULATOR_HOST: '127.0.0.1:8080', FIREBASE_AUTH_EMULATOR_HOST: '127.0.0.1:9099' });
initializeApp({ projectId: 'demo-timeline' });
const db = getFirestore();
const services = await (await fetch('http://127.0.0.1:4400/emulators')).json();
for (const service of ['auth', 'firestore', 'functions', 'storage', 'hosting']) assert.ok(services[service]);
const topics = (await db.collection('topics').get()).docs.map(d => d.id).sort();
const stories = (await db.collection('stories').count().get()).data().count;
const requests = (await db.collection('requests').count().get()).data().count;
const accounts = (await getAuth().listUsers()).users.length;
assert.deepEqual(topics, ['community', 'genshin-impact', 'zenless-zone-zero']);
assert.equal(stories, 0); assert.equal(requests, 0); assert.equal(accounts, 0);
await db.terminate();
const result = { at: new Date().toISOString(), status: 'PASS', project: 'demo-timeline', topics, stories, requests, accounts, ports: { zzz: 5173, timeline: 5174, hosting: 5000, emulatorUI: 4000 } };
await fs.writeFile('evidence/project-split/local-ready.json', JSON.stringify(result, null, 2));
console.log(JSON.stringify(result));
